// Write src/data/tts-sources.js: where each TTS model of the 3D table lives on the Steam
// CDN, so a browser can load the exact scans straight from Steam (the public site hosts
// no third-party assets, only these links). Bounds and material come from the packed
// public/models/manifest.json; URLs from the KT24 Killzone Mod save (Steam Workshop
// 3573927734); sizes and texture types from the CDN itself.
// Usage: npm run tts:sources [-- path/to/3573927734.bson]   (no path: fetch the save)
import { readFileSync, writeFileSync } from 'node:fs';
import { parseBSON } from '../src/import/tts.js';

const MOD = '3573927734';
const API = 'https://api.steampowered.com/ISteamRemoteStorage/GetPublishedFileDetails/v1/';
const CDN = 'cdn.steamusercontent.com';   // old saves name retired hosts; same paths work here
const cdn = u => u && u.replace(/^https?:\/\/[^/]*steamusercontent[^/]*\//, `https://${CDN}/`);   // other hosts kept
const key = u => { const p = (u || '').split('/').filter(Boolean); return p.length ? p[p.length - 1].slice(-16) : null; };

async function loadSave(path) {
  if (path) return readFileSync(path);
  const r = await fetch(API, { method: 'POST', body: new URLSearchParams({ itemcount: '1', 'publishedfileids[0]': MOD }) });
  const d = (await r.json()).response.publishedfiledetails[0];
  if (!d.file_url) throw new Error(`Workshop ${MOD} has no downloadable file (result ${d.result})`);
  console.log(`Workshop ${MOD}: ${d.title}`);
  return Buffer.from(await (await fetch(d.file_url)).arrayBuffer());
}
// total size and first bytes of a CDN file, from a 4-byte range request
async function probe(url) {
  const r = await fetch(url, { headers: { Range: 'bytes=0-3' } });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  const head = new Uint8Array(await r.arrayBuffer());
  const total = +((r.headers.get('content-range') || '').split('/')[1] || r.headers.get('content-length'));
  return { bytes: total, png: head[0] === 0x89 && head[1] === 0x50 };
}

const manifest = JSON.parse(readFileSync(new URL('../public/models/manifest.json', import.meta.url)));
const buf = await loadSave(process.argv[2]);
const save = parseBSON(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length));
// Only the twelve Volkus Approved Ops layout bags, as tools/fetch_assets.py picks them and
// tools/model_pack.py reads them (last object wins): one mesh can carry a different texture
// elsewhere in the mod — the game mat is the same mesh under every killzone's art.
const bags = [];
(function findBags(o) {
  if (!o || typeof o !== 'object') return;
  if (Array.isArray(o)) { o.forEach(findBags); return; }
  if (o.Name === 'Bag' && /^Volkus 2[45] 0[1-6]$/.test(o.Nickname || '') && (o.ContainedObjects || []).length >= 15) bags.push(o);
  for (const x in o) if (x !== 'LuaScript') findBags(o[x]);
})(save);
if (bags.length !== 12) throw new Error(`expected 12 Volkus layout bags, found ${bags.length}`);
const found = {};
for (const o of bags.flatMap(b => b.ContainedObjects)) {
  const cm = o.CustomMesh, ca = o.CustomAssetbundle;
  const k = key(cm && cm.MeshURL) || key(ca && ca.AssetbundleURL);
  if (!k || !manifest.models[k]) continue;
  const name = o.Nickname || (found[k] && found[k].name) || '';
  found[k] = { name, obj: cdn(cm && cm.MeshURL), tex: cdn(cm && cm.DiffuseURL), bundle: cdn(ca && ca.AssetbundleURL) };
}

const models = {};
for (const k of Object.keys(manifest.models).sort()) {
  const f = found[k], m = manifest.models[k];
  if (!f) throw new Error(`model ${k} is not in the save`);
  const e = { name: f.name, material: m.material, bounds: m.bounds };
  if (f.obj) {
    e.obj = f.obj; e.bytes = (await probe(f.obj)).bytes;
    if (f.tex) { const t = await probe(f.tex); e.tex = f.tex; e.texBytes = t.bytes; if (t.png) e.png = true; }
  } else { e.bundle = f.bundle; e.bytes = (await probe(f.bundle)).bytes; }   // Unity asset bundle (src/import/unity.js)
  models[k] = e;
  console.log(k, f.obj ? 'obj' : 'bundle', f.name);
}
const out = new URL('../src/data/tts-sources.js', import.meta.url);
writeFileSync(out, `/**
 * Steam CDN locations of the TTS models on the 3D table (KT24 Killzone Mod, Steam Workshop
 * ${MOD}). Generated by scripts/tts-sources.mjs — links only, no third-party content.
 */
export const TTS_SOURCES = {
${Object.entries(models).map(([k, e]) => ` ${JSON.stringify(k)}: ${JSON.stringify(e)},`).join('\n')}
};
`);
console.log(`wrote src/data/tts-sources.js (${Object.keys(models).length} models)`);
