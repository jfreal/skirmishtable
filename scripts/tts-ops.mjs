// Write src/data/tts-ops.js: the mission cards (Approved Ops 2024 and 2025: Tac Ops, Crit
// Ops, the Kill Op, initiative catch-up cards), the universal equipment cards and the token
// art from the KT24 Killzone Mod (Steam Workshop 3573927734), as Steam CDN links only. A TTS
// card is one cell of a sheet image (NumWidth x NumHeight); the browser cuts it out.
// Usage: npm run tts:ops [-- path/to/3573927734.bson]   (no path: fetch the save)
import { readFileSync, writeFileSync } from 'node:fs';
import { parseBSON } from '../src/import/tts.js';

const MOD = '3573927734';
const API = 'https://api.steampowered.com/ISteamRemoteStorage/GetPublishedFileDetails/v1/';
// retired Steam CDN hosts -> the current one; other hosts (imgur) are kept as they are
const cdn = u => u ? u.replace(/^https?:\/\/[^/]*steamusercontent[^/]*\//, 'https://cdn.steamusercontent.com/') : null;
const clean = s => (s || '').replace(/\[[^\]]*\]/g, '').trim();

async function loadSave(path) {
  if (path) return readFileSync(path);
  const r = await fetch(API, { method: 'POST', body: new URLSearchParams({ itemcount: '1', 'publishedfileids[0]': MOD }) });
  return Buffer.from(await (await fetch((await r.json()).response.publishedfiledetails[0].file_url)).arrayBuffer());
}
const buf = await loadSave(process.argv[2]);
const save = parseBSON(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length));
function find(o, pred) {
  if (!o || typeof o !== 'object') return null;
  if (Array.isArray(o)) { for (const v of o) { const r = find(v, pred); if (r) return r; } return null; }
  if (pred(o)) return o;
  for (const k in o) if (k !== 'LuaScript' && k !== 'XmlUI') { const r = find(o[k], pred); if (r) return r; }
  return null;
}
// one card: its sheet, the cell on it, and the back
function card(o) {
  const id = Math.floor(o.CardID / 100), d = o.CustomDeck[id] || Object.values(o.CustomDeck)[0];
  const c = { name: clean(o.Nickname), sheet: cdn(d.FaceURL), cols: d.NumWidth, rows: d.NumHeight, i: o.CardID % 100,
              back: cdn(d.BackURL) };
  if (o.SidewaysCard) c.sideways = true;
  if (o.Description) c.text = o.Description.trim();
  return c;
}
const uniq = list => [...new Map(list.map(c => [c.name, c])).values()];
const hb = find(save.ObjectStates, o => o.Name === 'Bag' && clean(o.Nickname) === 'Hidden bag Approved Ops Horizontal');
const sets = [];
for (const name of ['Approved Ops 2025', 'Approved Ops 2024']) {
  const bag = find(hb, o => clean(o.Nickname) === name && (o.ContainedObjects || []).length);
  const items = bag.ContainedObjects;
  const cards = items.filter(o => /^Card/.test(o.Name) && o.CustomDeck).map(card);
  const deck = items.find(o => o.Name === 'Deck');
  const crit = deck.ContainedObjects.map(card).map(c => ({ ...c, name: c.name.replace(/^\d+\.?\s*/, '') }));
  const tac = uniq(cards.filter(c => !/^(Crit Op|Tac Op|Kill Op|Re-Roll|[+-]\d|\d+ - )/.test(c.name)));
  const kill = cards.find(c => c.name === 'Kill Op');
  const extras = uniq(cards.filter(c => /^(Re-Roll|\+\d)/.test(c.name)));
  sets.push({ name, tac, crit, kill, extras });
  console.log(`${name}: ${tac.length} tac, ${crit.length} crit, kill ${!!kill}, ${extras.length} extras`);
}
// universal equipment: one card per bag in a team's equipment bag
const eqBag = find(save.ObjectStates, o => o.Name === 'Bag' && clean(o.Nickname) === 'Equipment Bag Blue');
const equipment = (eqBag ? eqBag.ContainedObjects : []).map(b => {
  const c = find(b, o => /^Card/.test(o.Name) && o.CustomDeck);
  return c && { ...card(c), name: clean(b.Nickname) };
}).filter(Boolean);
console.log(`equipment: ${equipment.length}`);
// token art (grenades, markers, mission tokens): name -> image, one of each
const tokens = new Map();
(function visit(o) {
  if (!o || typeof o !== 'object') return;
  if (Array.isArray(o)) { o.forEach(visit); return; }
  if (o.Name === 'Custom_Token' && o.CustomImage && o.CustomImage.ImageURL) {
    const n = clean(o.Nickname).replace(/_/g, ' ').replace(/\s+\d+$/, '').trim();
    if (n && !tokens.has(n.toLowerCase())) tokens.set(n.toLowerCase(), { name: n, img: cdn(o.CustomImage.ImageURL) });
  }
  for (const k in o) if (k !== 'LuaScript' && k !== 'XmlUI') visit(o[k]);
})(save.ObjectStates);
// game pieces only: no TTS tools (range tool, board rotation, UI extenders) or duplicates
const tokenList = [...tokens.values()]
  .filter(t => !/info|tracker|turn order|status|range tool|rotate board|autoextender|threat level|^smoke nade$/i.test(t.name))
  .sort((a, b) => a.name.localeCompare(b.name));
console.log(`tokens: ${tokenList.length}`);
const out = new URL('../src/data/tts-ops.js', import.meta.url);
writeFileSync(out, `/**
 * Mission and equipment cards and token art from the KT24 Killzone Mod (Steam Workshop ${MOD}):
 * each card is cell \`i\` of a \`cols\` x \`rows\` sheet image on the Steam CDN. Generated by
 * scripts/tts-ops.mjs — links only, no third-party content.
 */
export const TTS_OPS = ${JSON.stringify({ sets, equipment, tokens: tokenList }, null, 1)};
`);
console.log('wrote src/data/tts-ops.js');
