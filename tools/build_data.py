#!/usr/bin/env python3
"""Write the app's generated data modules from the pipeline outputs:

  src/data/fine-pieces.js     per-piece 0.1" footprint rasters (from fine_footprint.py),
                              with the fire-step mesh recoded as non-blocking 'step' and
                              the scanned light rubble kept as light terrain only
  src/data/volkus-layouts.js  the twelve Volkus Approved Ops layouts (2024 and 2025) as
                              trimmed TTS placements: [mesh key, posX, posZ, rotY, scale]

Usage: python tools/build_data.py   (after fetch_assets.py and fine_footprint.py)
"""
import base64, json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import volkus_convert as V
from fine_footprint import encode
from paths import FINE_DIR, PARSED_DIR, SRC_DATA, write_js_module

def decode(e):
    raw = base64.b64decode(e["rle"]); flat = []
    for i in range(0, len(raw), 2): flat += [raw[i]] * raw[i + 1]
    return np.array(flat, np.uint8).reshape(e["nz"], e["nx"])

def fine_table(table):
    fine = {}
    for k, e in table.items():
        codes = decode(e); cls, zq = codes >> 4, codes & 15
        if k in V.STEP_MESHES:      # fire steps: Insignificant/Exposed platforms, never block
            cls = np.where(cls > 0, 4, 0).astype(np.uint8); zq = np.where(cls > 0, 1, 0)
        if k in V.LIGHT_MESHES:     # scanned light rubble: light only
            cls = np.where((cls == 1) | (cls == 3), 3, np.where(cls == 5, 0, cls)).astype(np.uint8)
        fine[k] = [e["s0"], e["x0"], e["z0"], e["nx"], e["nz"], encode(cls, zq / 2.0)]
    return fine

def layouts(bags):
    out = {}
    for yr, prefix in ((24, "v"), (25, "y")):
        for i in range(1, 7):
            nick = f"Volkus {yr} 0{i}"; items = []
            for o in bags[nick]["ContainedObjects"]:
                k = V.key_of(o)
                if not k: continue
                t = o["Transform"]
                # [key, posX, posZ, rotY, scaleX] for the rules engine, then what the 3D table
                # needs to place the exact model: posY, rotX, rotZ, scaleY, scaleZ, tint RGBA
                item = [k, round(t["posX"], 4), round(t["posZ"], 4), round(t["rotY"], 3), round(t["scaleX"], 4),
                        round(t["posY"], 4), round(t.get("rotX", 0), 3), round(t.get("rotZ", 0), 3),
                        round(t.get("scaleY", t["scaleX"]), 4), round(t.get("scaleZ", t["scaleX"]), 4)]
                c = o.get("ColorDiffuse") or {}
                tint = [round(c.get(ch, 1.0), 3) for ch in ("r", "g", "b", "a")]
                if tint != [1.0, 1.0, 1.0, 1.0]: item.append(tint)
                items.append(item)
            name = f"Volkus AO {i}" if yr == 24 else f"Volkus '25 AO {i}"
            out[f"{prefix}{i}"] = {"name": name, "nick": nick, "items": items}
    return out

if __name__ == "__main__":
    table = json.load(open(os.path.join(FINE_DIR, "fine_pieces.json")))
    bags = json.load(open(os.path.join(PARSED_DIR, "volkus_bags.json")))
    write_js_module(os.path.join(SRC_DATA, "fine-pieces.js"),
        "GENERATED by tools/build_data.py — do not edit. Per-piece 0.1\" footprint rasters\n"
        "traced from the TTS scans: [typical scale, x0, z0, nx, nz, RLE of (class<<4 | height\n"
        "in half inches)], classes 1 wall, 2 heavy, 3 light, 4 step, 5 upper floor overhead.",
        "FINE_PIECES", fine_table(table))
    write_js_module(os.path.join(SRC_DATA, "volkus-layouts.js"),
        "GENERATED by tools/build_data.py — do not edit. Volkus Approved Ops layouts (2024 and\n"
        "2025) as TTS placements: [key, posX, posZ, rotY, scaleX, posY, rotX, rotZ, scaleY,\n"
        "scaleZ, tint?] per object (the last six place the exact 3D models).",
        "VOLKUS_LAYOUTS", layouts(bags))
