#!/usr/bin/env python3
"""Convert extracted TTS Gallowdark map objects into the sandbox's Gallowdark maps.
The in-app importer (convertGallowdark in src/import/tts.js) does the same in JS.

Coordinate mapping: TTS table units are inches, board centred on origin,
x = short axis (6 cells), z = long axis (7 cells), cell = 3.78", half-cell 1.89".
Sandbox wants landscape with origin at top-left: X = tts_z + 13.23, Y = tts_x + 11.34.
Horizontal TTS pieces (rotY 0/180, run along tts-x) become vertical in the sandbox.
Kind B pieces are hatchways: two stubs with a passable opening.
"""
import json, sys

KIND = {"EE73153AEE143847EBBF": "A", "207C7AB5934D67BEB61E": "B", "C2C86C4F97C6EB4F9A22": "C"}
LEN, THICK, WALL_Z = 1.89, 0.25, 4
OPENING = 1.4                      # hatchway gap (base diameter is 1.102")
STUB = (LEN - OPENING) / 2
BOARD_W, BOARD_H = 26.46, 22.68    # 7 x 6 cells after rotation
HX, HZ = 11.34, 13.23              # TTS half-extents (x short, z long)

def convert(objs, name, source):
    walls, objectives, idn = [], [], 0
    for o in objs:
        t = o["Transform"]
        x, z, rot = t["posX"], t["posZ"], round(t["rotY"]) % 360
        if o["Name"] == "Custom_Token":
            if abs(x) <= HX + 0.3 and abs(z) <= HZ + 0.3:
                objectives.append({"id": f"OBJ-{len(objectives)+1}",
                                   "x": round(z + HZ, 2), "y": round(x + HX, 2)})
            continue
        if o["Name"] != "Custom_Assetbundle":
            continue
        if abs(x) > HX + 0.3 or abs(z) > HZ + 0.3:
            continue  # spare piece parked off the board
        ab = (o.get("CustomAssetbundle") or {}).get("AssetbundleURL") or ""
        kind = KIND.get(ab.rsplit("/", 2)[-2][:20], "A")
        X, Y = z + HZ, x + HX
        vertical_in_sandbox = rot in (0, 180, 181)   # ran along tts-x
        def rect(cx, cy, length, idn):
            if vertical_in_sandbox:
                r = {"x": cx - THICK/2, "y": cy - length/2, "w": THICK, "h": length}
            else:
                r = {"x": cx - length/2, "y": cy - THICK/2, "w": length, "h": THICK}
            # clamp to the board so edge pieces don't spill outside the play area
            x0, y0 = max(0.0, r["x"]), max(0.0, r["y"])
            x1, y1 = min(BOARD_W, r["x"] + r["w"]), min(BOARD_H, r["y"] + r["h"])
            if x1 - x0 < 0.08 or y1 - y0 < 0.08:
                return None
            return {"id": f"G{idn}", "kind": "wall", "noclimb": True, "z": WALL_Z,
                    "x": round(x0, 3), "y": round(y0, 3),
                    "w": round(x1 - x0, 3), "h": round(y1 - y0, 3)}
        if kind == "B":  # hatchway: two stubs around an open access point
            off = (OPENING + STUB) / 2
            d = (0, off) if vertical_in_sandbox else (off, 0)
            for sx, sy in ((X - d[0], Y - d[1]), (X + d[0], Y + d[1])):
                r = rect(sx, sy, STUB, idn)
                if r: walls.append({**r, "hatch": True}); idn += 1
        else:
            r = rect(X, Y, LEN, idn)
            if r: walls.append(r); idn += 1
    return {"name": name, "source": source, "w": BOARD_W, "h": BOARD_H,
            "dropDepth": 3.78, "cell": 3.78, "terrain": walls, "objectives": objectives}

if __name__ == "__main__":
    # python tools/convert_maps.py  ->  src/data/gallowdark.js  (run fetch_assets.py first)
    import os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from paths import GALLOWDARK_MODS, PARSED_DIR, SRC_DATA, write_js_module
    out = {}
    for key, (item_id, name) in GALLOWDARK_MODS.items():
        m = convert(json.load(open(os.path.join(PARSED_DIR, f"gallowdark_{key}.json"))), name, f"Steam Workshop {item_id}")
        out[key] = m
        print(f"{key}: {len(m['terrain'])} wall rects ({sum(1 for w in m['terrain'] if w.get('hatch'))//2} hatchways), {len(m['objectives'])} objectives")
    write_js_module(os.path.join(SRC_DATA, "gallowdark.js"),
        "GENERATED by tools/convert_maps.py — do not edit. Gallowdark Approved Ops 1-2 from the TTS\n"
        "saves (Steam Workshop 3353224453, 3360436479): each wall piece is an axis-aligned rect,\n"
        "hatchways are two stubs around an open access point; walls are 4\" noclimb bulkheads.",
        "GDMAPS", out)
